const NOW = new Date('2026-10-26T10:00:00+05:30')

function at(daysAgo: number, hour = 10): string {
  const d = new Date(NOW)
  d.setDate(d.getDate() - daysAgo)
  d.setHours(hour, 0, 0, 0)
  return d.toISOString()
}

function plusDays(iso: string, days: number): string {
  const d = new Date(iso)
  d.setDate(d.getDate() + days)
  return d.toISOString()
}

function event(
  id: string,
  type: TimelineType,
  title: string,
  description: string,
  actor: string,
  daysAgo: number,
  visibility: TimelineEvent['visibility'] = 'Internal',
): TimelineEvent {
  return { id, type, title, description, actor, at: at(daysAgo), visibility }
}

function doc(
  id: string,
  name: string,
  kind: CaseDocument['kind'],
  size: string,
  daysAgo: number,
  uploadedBy: string,
  sealed = false,
): CaseDocument {
  return { id, name, kind, size, uploadedAt: at(daysAgo), uploadedBy, sealed }
}

