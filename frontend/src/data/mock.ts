interface CaseSeed {
  id: string
  caseNo: string
  institutionId: string
  title: string
  category: string
  subcategory: string
  bureau: Bureau
  status: CaseStatus
  severity: Severity
  confidentiality?: CaseRecord['confidentiality']
  receivedDaysAgo: number
  slaDays: number
  officer: string
  lastAction: string
  lastActionDaysAgo: number
  nextAction: string
  nextActionDays: number
  source: string
  summary: string
  tags: string[]
  linkedCaseIds?: string[]
  timeline?: TimelineEvent[]
  documents?: CaseDocument[]
}

function makeTimeline(seed: CaseSeed): TimelineEvent[] {
  if (seed.timeline) return seed.timeline
  const sealed = seed.confidentiality === 'Sealed'
  const receivedAt = at(seed.receivedDaysAgo)
  const base: TimelineEvent[] = [
    {
      id: `${seed.id}-t1`,
      type: 'intake',
      title: 'Complaint received',
      description: `Received via ${seed.source}. Complaint registered against the institution.`,
      actor: 'Intake desk',
      at: receivedAt,
      visibility: sealed ? 'Sealed' : 'Internal',
    },
    {
      id: `${seed.id}-t2`,
      type: 'triage',
      title: 'AI triage completed',
      description: `Classified as ${seed.category} · ${seed.severity.toLowerCase()} severity. Suggested owner: ${seed.bureau}.`,
      actor: 'Samanvay Assist',
      at: plusDays(receivedAt, 0.08),
      visibility: sealed ? 'Sealed' : 'Internal',
    },
    {
      id: `${seed.id}-t3`,
      type: 'assignment',
      title: `Assigned to ${seed.officer}`,
      description: `${seed.bureau} accepted ownership. Institution identity confirmed against AICTE Permanent ID.`,
      actor: 'Auto-routing',
      at: plusDays(receivedAt, 1),
      visibility: sealed ? 'Sealed' : 'Internal',
    },
  ]
  if (seed.status !== 'New' && seed.status !== 'Triaged') {
    base.push({
      id: `${seed.id}-t4`,
      type: seed.status === 'Disposed' ? 'closure' : seed.status === 'Transferred' ? 'transfer' : 'action',
      title: seed.lastAction,
      description: seed.status === 'Disposed'
        ? 'Case disposed after due process. Disposal order recorded and communicated.'
        : seed.status === 'Transferred'
          ? 'Case transferred to the appropriate regional office with complete case history.'
          : `Latest action recorded by ${seed.bureau}. Next step: ${seed.nextAction.toLowerCase()}.`,
      actor: seed.officer,
      at: at(seed.lastActionDaysAgo),
      visibility: sealed ? 'Sealed' : 'Internal',
    })
  }
  return base
}

function makeDocs(seed: CaseSeed): CaseDocument[] {
  if (seed.documents) return seed.documents
  return [
    doc(`${seed.id}-d1`, `${seed.caseNo.replaceAll('/', '-')}-complaint.pdf`, 'PDF', '1.8 MB', seed.receivedDaysAgo, 'Intake desk', seed.confidentiality === 'Sealed'),
    doc(`${seed.id}-d2`, 'Institution-response.pdf', 'PDF', '2.4 MB', Math.max(1, seed.lastActionDaysAgo), seed.officer, seed.confidentiality === 'Sealed'),
  ]
}

